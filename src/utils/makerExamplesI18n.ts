/**
 * Get random maker example for current language
 */
export function getRandomMakerExample(languageCode: string): string {
  const lang = languageCode.split('-')[0]; // Handle zh-CN → zh
  const examples = MAKER_EXAMPLES_BY_LANGUAGE[lang] || MAKER_EXAMPLES_BY_LANGUAGE['en'];
  return examples[Math.floor(Math.random() * examples.length)];
}

/**
 * Get multiple examples for placeholder text
 */
export function getMakerExamplesForPlaceholder(languageCode: string, count: number = 2): string {
  const lang = languageCode.split('-')[0];
  const examples = MAKER_EXAMPLES_BY_LANGUAGE[lang] || MAKER_EXAMPLES_BY_LANGUAGE['en'];
  
  const selected: string[] = [];
  const used = new Set<number>();
  
  while (selected.length < count && used.size < examples.length) {
    const index = Math.floor(Math.random() * examples.length);
    if (!used.has(index)) {
      used.add(index);
      selected.push(examples[index]);
    }
  }
  
  return selected.join(', ');
}

